"""Build data/library/songs.json and data/ATTRIBUTION.md from the lyric files and descriptions.json.

    .venv/bin/python scripts/build_song_list.py

Reads whatever is in data/library/lyrics/ (written by a separate session; this script never writes there) and
every record in data/library/descriptions.json. songs.json lists every song with genre, mood and energy values
(genre_label is the real genre with its source; genre is the nearest songs.csv word for the scorer; mood and energy
are labeled estimates, kept by Danny on Nov 18, 2026). It carries no approval flag for descriptions: the index
builder reads that from descriptions.json, so the two files cannot disagree.
"""
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional

try:
    from scripts.library_catalog import MODERN, PUBLIC_DOMAIN_ATTRS, slugify
except ImportError:  # running as `python scripts/build_song_list.py`
    from library_catalog import MODERN, PUBLIC_DOMAIN_ATTRS, slugify

ROOT = Path(__file__).resolve().parent.parent
LYRICS_DIR = ROOT / "data" / "library" / "lyrics"
DESCRIPTIONS = ROOT / "data" / "library" / "descriptions.json"
SONGS_JSON = ROOT / "data" / "library" / "songs.json"
ATTRIBUTION = ROOT / "data" / "ATTRIBUTION.md"
MODERN_BY_ID = {e["id"]: e for e in MODERN}


ACCEPTED = "Danny, 2026-11-18"


def _values(attrs: Optional[Dict]) -> Dict:
    """The genre/mood/energy fields for one song. Unknown songs get None everywhere so they are filled in by hand."""
    if not attrs:
        return {"genre_label": None, "genre_label_source": None, "genre": None, "mood": None, "energy": None,
                "mood_energy_source": None, "accepted": None}
    return {"genre_label": attrs.get("genre_label"), "genre_label_source": attrs.get("genre_label_source"),
            "genre": attrs["genre"], "mood": attrs["mood"], "energy": attrs["energy"],
            "mood_energy_source": "estimate", "accepted": ACCEPTED}


def parse_lyrics_file(path: Path) -> Dict:
    """Header lines (title/year/source/fetched), a blank line, then verses separated by blank lines."""
    head, _, body = path.read_text(encoding="utf-8").partition("\n\n")
    header = {}
    for line in head.splitlines():
        key, _, value = line.partition(":")
        header[key.strip().lower()] = value.strip()
    year = header.get("year", "")
    return {"slug": path.stem, "title": header.get("title", path.stem), "year": int(year) if year.isdigit() else None,
            "source": header.get("source"), "fetched": header.get("fetched"),
            "verses": [v.strip() for v in body.split("\n\n") if v.strip()]}


def build_records(lyrics_dir: Path, descriptions_path: Path) -> List[Dict]:
    """One record per song: lyric songs first (alphabetical by file), then descriptions in the catalog's order."""
    records: List[Dict] = []
    if lyrics_dir.is_dir():
        for path in sorted(lyrics_dir.glob("*.txt")):
            lyric = parse_lyrics_file(path)
            attrs = PUBLIC_DOMAIN_ATTRS.get(slugify(lyric["title"]))
            records.append({"id": slugify(lyric["title"]), "title": lyric["title"], "artist": None,
                            "year": lyric["year"], "kind": "lyrics", "source": lyric["source"], **_values(attrs)})
    drafted = json.loads(descriptions_path.read_text(encoding="utf-8")) if descriptions_path.exists() else []
    order = {e["id"]: i for i, e in enumerate(MODERN)}
    for item in sorted(drafted, key=lambda r: order.get(r["id"], len(order))):
        entry = MODERN_BY_ID.get(item["id"])
        records.append({"id": item["id"], "title": item.get("title", (entry or {}).get("title")),
                        "artist": item.get("artist"), "year": item.get("year"), "kind": "description",
                        "source": item["wikipedia_url"], **_values(entry)})
    return records


def render_attribution(records: List[Dict], descriptions: List[Dict]) -> str:
    """The credits file: Wikipedia (CC BY-SA 4.0) for descriptions, a named source for each public-domain lyric."""
    revisions = {d["id"]: d.get("revision_id") for d in descriptions}
    lines = [
        "# Attribution",
        "",
        "<!-- Generated by scripts/build_song_list.py from data/library/. Re-run it instead of editing by hand. -->",
        "",
        "## Song descriptions (Wikipedia, CC BY-SA 4.0)",
        "",
        "Song descriptions in `data/library/descriptions.json` are AI-written summaries (Google Gemini) of the linked "
        "English Wikipedia articles, then reviewed and edited by the student. The text was changed from the originals. "
        "Wikipedia text © Wikipedia contributors, licensed under CC BY-SA 4.0. These descriptions are shared under "
        "CC BY-SA 4.0: https://creativecommons.org/licenses/by-sa/4.0/",
        "",
    ]
    for rec in (r for r in records if r["kind"] == "description"):
        lines.append(f"- {rec['title']}: {rec['source']} (revision {revisions.get(rec['id'])})")
    lines += [
        "",
        "## Lyrics (public domain)",
        "",
        "Public domain in the US: words published in 1930 or earlier. Each song's verses were copied from the source "
        "linked below: a Wikisource page, or, where marked, a Wikipedia article that quotes the original text of that "
        "year. Only 1 to 3 verses of each song are kept. Recordings and later arrangements are not used. "
        "The Batman playground parody of Jingle Bells (1960s) is not public domain, so none of its lines are stored; "
        "it appears only as a description.",
        "",
    ]
    lyric_records = [r for r in records if r["kind"] == "lyrics"]
    for rec in lyric_records:
        year = f" ({rec['year']})" if rec.get("year") else ""
        note = ""
        if "wikipedia.org" in (rec.get("source") or ""):
            when = f"the {rec['year']} text" if rec.get("year") else "the original text"
            note = f" (copied from this Wikipedia article, which quotes {when})"
        lines.append(f"- {rec['title']}{year}: {rec['source']}{note}")
    lines += [
        "",
        "## Genre, mood and energy values",
        "",
        "`data/library/songs.json` gives each song four values. `genre_label` is the song's real genre, copied from "
        "the Wikipedia infobox or article intro where one was found (`genre_label_source` says which) and otherwise "
        "an estimate. `genre` is only the nearest word in the 16-word vocabulary of `data/songs.csv`, so the Project 3 "
        "scorer can use it; it is a mapping, not a claim about the song. `mood` and `energy` (0 to 1) are estimates "
        "with no source: proposed by the build session (Claude) on Nov 17, 2026 and kept by Danny on Nov 18, 2026.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    records = build_records(LYRICS_DIR, DESCRIPTIONS)
    descriptions = json.loads(DESCRIPTIONS.read_text(encoding="utf-8")) if DESCRIPTIONS.exists() else []
    SONGS_JSON.parent.mkdir(parents=True, exist_ok=True)
    SONGS_JSON.write_text(json.dumps(records, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    ATTRIBUTION.write_text(render_attribution(records, descriptions), encoding="utf-8")
    lyric_n = sum(r["kind"] == "lyrics" for r in records)
    print(f"Wrote {len(records)} songs to {SONGS_JSON.relative_to(ROOT)} ({lyric_n} lyric, {len(records) - lyric_n} description)")
    for rec in records:
        if rec["genre"] is None:
            print(f"  note: {rec['id']} is not in the catalog; genre/mood/energy left blank for review", file=sys.stderr)
    if not lyric_n:
        print("  note: data/library/lyrics/ is empty or missing; lyric songs are added by the other session", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
